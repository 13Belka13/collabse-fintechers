# Two-level explanations of a decision (SPEC §6.7). Template text is instant and always available;
# AI text (MODEL_FAST) is optional, must cite only the decision's own source URLs, and is labelled
# (AI Act Art. 50). The client audience only ever sees what codes.client_view lets through.
import json
import re

from pydantic import BaseModel, ConfigDict

from bank import codes, llm
from bank.codes import Code

AI_LABEL = "Generated by AI (AI Act Art. 50) / Vygenerováno AI"

HEADLINES = {
    Code.MANDATE_NOT_ACTIVE: "The mandate is not active",
    Code.MANDATE_EXPIRED: "The mandate has expired",
    Code.CATEGORY_NOT_IN_SCOPE: "This purchase is outside the mandate's scope",
    Code.COUNTERPARTY_NOT_IN_SCOPE: "The payee is not the registered seller",
    Code.COUNTERPARTY_NOT_TRUSTED: "The seller did not pass the bank's checks",
    Code.AMOUNT_ABOVE_LIMIT: "The amount is above the limit",
    Code.BUDGET_EXCEEDED: "The mandate budget would be exceeded",
    Code.QUOTE_MISMATCH: "The payment request does not match the agreed offer",
    Code.VELOCITY_EXCEEDED: "Too many payments in a short time",
    Code.CONFIRMATION_REQUIRED: "A human must confirm this payment",
    Code.VAT_LIABILITY_RISK: "VAT liability risk (Czech VAT Act §109)",
    Code.UNDER_REVIEW: "The payment is under review at the bank",
}
NEXT_STEP = {
    "amend_mandate": "Next: a human can amend the mandate.",
    "ask_human": "Next: a human decides.",
    "retry_later": "Next: try again later.",
    "confirm": "Next: a human confirms the payment.",
    "confirm_or_pay_in_tczk": "Next: a human acknowledges the VAT risk once, or the deal is paid in tCZK.",
}
# Words that must never reach a client text (no tipping-off, §38 AML Act) — a second net behind client_view.
CLIENT_FORBIDDEN = ("sanction", "sankc", "aml", "laundering", "praní", "suspic", "podezř", "near match", "non-public")

SYSTEM = (
    "You explain a bank's payment decision in 2-3 plain sentences, in English. Use only the facts in the "
    "decision JSON. Cite only URLs that appear in it. Reply with JSON only: "
    '{"text": "...", "cited_sources": ["https://..."]}'
)


class Explanation(BaseModel):
    model_config = ConfigDict(extra="forbid")
    text: str
    cited_sources: list[str]


def _is_neutral(decision: dict) -> bool:
    """True when the client may only get the neutral 'under review' answer."""
    return codes.client_view({**decision, "explanation": ""})["explanation"] == codes.NEUTRAL_CLIENT_TEXT


def sources(decision: dict) -> list[str]:
    seen = []
    for r in decision.get("reasons", []):
        if r.get("source_url") and r["source_url"] not in seen:
            seen.append(r["source_url"])
    return seen


def template(decision: dict, audience: str = "compliance") -> str:
    if audience == "client" and _is_neutral(decision):
        return codes.NEUTRAL_CLIENT_TEXT
    if decision["status"] == "ok":
        text = "Payment approved: it is within the mandate and the seller passed the bank's checks."
    else:
        text = HEADLINES.get(decision.get("code"), "The payment was not approved") + "."
        parts = []
        for r in decision.get("reasons", []):
            tag = "" if r.get("public") is True else " [non-public, compliance only]"
            parts.append(r["text"] + tag)
        if parts:
            text += " " + " ".join(p if p.endswith(".") else p + "." for p in parts)
    for mark in decision.get("marks", []):
        text += f" Note: {mark}."
    if decision.get("next_tool") in NEXT_STEP:
        text += " " + NEXT_STEP[decision["next_tool"]]
    return text


def _leaks(text: str) -> bool:
    low = text.lower()
    return any(re.search(rf"\b{re.escape(w)}", low) for w in CLIENT_FORBIDDEN)


def render(decision: dict, audience: str = "client", deal_id: str | None = None, ai: bool = False) -> dict:
    """{"text", "cited_sources", "ai_generated"(, "label")}. Template first; with ai=True the model's text
    replaces it only if it cites a subset of the decision's sources and (client) leaks nothing."""
    if audience not in ("client", "compliance"):
        raise ValueError(f"unknown audience {audience!r}")
    neutral = audience == "client" and _is_neutral(decision)
    out = {"text": template(decision, audience), "cited_sources": [] if neutral else sources(decision),
           "ai_generated": False}
    if not ai or neutral:
        return out  # nothing to explain to a client beyond the neutral text — never ask a model about it
    data = codes.client_view(decision) if audience == "client" else decision
    if audience == "client":
        data = {**data, "marks": decision.get("marks", [])}
    allowed = set(sources(data))
    prompt = f"Audience: {audience}.\nDecision JSON:\n{json.dumps(data, ensure_ascii=False, default=str)}"
    value, ok = llm.json_call("fast", SYSTEM, prompt, Explanation, None, stage="explain",
                              deal_id=deal_id or decision.get("deal_id"))
    if not ok or not value.text.strip() or not set(value.cited_sources) <= allowed:
        return out
    if not set(re.findall(r"https?://[^\s)\]>\"']+", value.text)) <= allowed:  # a link not in the evidence
        return out
    if audience == "client" and _leaks(value.text):
        return out
    return {"text": value.text, "cited_sources": value.cited_sources, "ai_generated": True, "label": AI_LABEL}


def _mock_explain(messages, tools):
    prompt = messages[-1]["content"]
    code = re.search(r'"code": "([A-Z_]+)"', prompt)
    urls = list(dict.fromkeys(re.findall(r'"source_url": "([^"]+)"', prompt)))
    text = (f"The bank stopped this payment ({code.group(1)}). The cited sources show why." if code
            else "The bank approved this payment within the mandate.")
    return {"text": json.dumps({"text": text, "cited_sources": urls})}


llm.register_mock("explain", _mock_explain)
